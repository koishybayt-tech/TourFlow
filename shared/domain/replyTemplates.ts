/** Quick reply templates for the inbox. {name} is replaced with the client's first name. */
export const REPLY_TEMPLATES = [
  { title: 'Приветствие', text: 'Здравствуйте, {name}! Это Demo Travel, меня зовут {manager}. Спасибо за обращение — подскажите, пожалуйста, желаемые даты, сколько вас человек и есть ли действующая виза?' },
  { title: 'Программа тура', text: '{name}, отправляю программу тура и что входит в стоимость. Если удобно, созвонимся — расскажу подробнее.' },
  { title: 'Документы для визы', text: '{name}, для визы понадобятся: загранпаспорт (действует 6 месяцев после поездки), фото 3,5×4,5, справка с работы, выписка со счёта за 6 месяцев.' },
  { title: 'Реквизиты для оплаты', text: '{name}, предоплату можно внести через Kaspi по номеру +7 727 300 10 20 или переводом на счёт. После оплаты пришлите, пожалуйста, чек.' },
  { title: 'Подборка отправлена', text: '{name}, отправила подборку вариантов. Цены актуальны сегодня — дайте знать, какой вариант понравился, и я забронирую.' },
] as const

export function fillReply(text: string, vars: { name?: string, manager?: string }): string {
  return text.replace('{name}', (vars.name ?? '').split(' ')[0] || '').replace('{manager}', vars.manager ?? '')
}
